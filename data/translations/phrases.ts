/**
 * Helper to translate any phrase dynamically.
 * Falls back to English if the key or language is missing.
 */
export function translatePhrase(
  phrase: string,
  lang: LanguageCode = "en"
): string {
  if (!phrase) return "";
  const entry = phraseDictionary[phrase.trim()];
  if (entry && entry[lang]) {
    return entry[lang];
  }
  return phrase;
}
